package com.mclegoman.perspective.mixin.client.textured_entity;

import com.mclegoman.perspective.client.entity.TexturedEntity;
import net.minecraft.client.render.GameRenderer;
import net.minecraft.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(GameRenderer.class)
public class GameRendererMixin {
	@Inject(method = "onCameraEntitySet", at = @At("RETURN"))
	private void perspective$onCameraEntitySet(Entity entity, CallbackInfo ci) {
		TexturedEntity.applyShader();
	}
}
